// common.js — shared helpers for life-tracker load tests.
//
// Base URL is configurable so the same scripts can target:
//   - the direct backend:    http://localhost:8080  (compose `api` container)
//   - the full stack (nginx):http://localhost:3000  (frontend proxy -> api)
//
// Set LOADTEST_BASE_URL to override (see README.md).

import { SharedArray } from 'k6/data';
import { sleep } from 'k6';

export const BASE_URL = (__ENV.LOADTEST_BASE_URL || 'http://localhost:8080').replace(/\/+$/, '');

export const USERS_FILE = __ENV.LOADTEST_USERS_FILE || 'users.json';

// Default password used for every provisioned user.
export const PASSWORD = 'lt-pass-123';

// Load the user pool written by provision.js (one JSON object per line).
// Must be called from init context. Each VU is mapped to one user, so every
// VU acts as a distinct real account — no token contention.
export function loadUserPool() {
  let raw;
  try {
    raw = open(USERS_FILE);
  } catch (e) {
    throw new Error(`cannot read user pool "${USERS_FILE}": ${e.message}. Run "make provision" first.`);
  }
  const users = raw
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => JSON.parse(l));
  if (users.length === 0) {
    throw new Error(`user pool "${USERS_FILE}" is empty. Run "make provision" first.`);
  }
  return new SharedArray('users', () => users);
}

// Deterministic per-VU identity: VU n acts as user pool[n % len].
export function userForVU(pool) {
  return pool[(__VU - 1) % pool.length];
}

export function authHeaders(token) {
  return {
    Authorization: `Bearer ${token}`,
    'Content-Type': 'application/json',
  };
}

export function jsonHeaders() {
  return { 'Content-Type': 'application/json' };
}

// Unique user payload for registration. `prefix` must match ^[a-z0-9_]+$ and the
// username stays within 3-30 lowercase/digit/underscore chars (server rule).
export function userPayload(prefix, seq) {
  const username = `${prefix}_${seq}`;
  return {
    email: `${username}@loadtest.local`,
    firstName: 'Load',
    lastName: 'Test',
    username,
    password: PASSWORD,
  };
}

export function activityPayload() {
  return {
    title: `Load activity ${__ITER}`,
    description: 'generated by loadtest',
    frequency: 'daily',
    dayFrequency: 'monday',
    dayTime: 'evening',
    completionAmount: 1,
  };
}

export function recordPayload() {
  return {
    completionDate: new Date().toISOString(),
    notes: 'loadtest record',
  };
}

export function notePayload() {
  return {
    title: `Load note ${__ITER}`,
    content: 'generated by loadtest',
  };
}

export function transactionPayload() {
  return {
    type: 'outcome',
    frequency: 'variable',
    description: 'loadtest transaction',
    amount: 100 + (__ITER % 900),
    // must match one of the server's predefined categories
    category: 'Food & Groceries',
    date: new Date().toISOString(),
  };
}

// Query-parameter date format expected by summary endpoints (YYYY-MM-DD).
export function todayISO() {
  return new Date().toISOString().slice(0, 10);
}

// Random sleep in seconds for per-VU rhythm scripts (k6 `sleep` is synchronous).
export function sleepBetween(minS, maxS) {
  sleep(minS + Math.random() * (maxS - minS));
}
